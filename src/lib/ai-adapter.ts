// ============================================================
// HAQ — AI Adapter (Provider-Independent)
// Configurable AI provider that can be switched without
// rewriting the application. Supports Gemini and a fallback
// mock provider for demo mode.
// ============================================================

export interface AIMessage {
  role: "system" | "user" | "assistant";
  content: string;
}

export interface AIResponse {
  content: string;
  provider: string;
  model: string;
  tokensUsed?: number;
  error?: string;
}

export interface AIProvider {
  name: string;
  generateCompletion(
    messages: AIMessage[],
    options?: { temperature?: number; maxTokens?: number }
  ): Promise<AIResponse>;
  isAvailable(): Promise<boolean>;
}

// --------------------------------------------------
// Mock / Demo Provider
// --------------------------------------------------
class MockAIProvider implements AIProvider {
  name = "mock";

  async generateCompletion(
    messages: AIMessage[],
    _options?: { temperature?: number; maxTokens?: number }
  ): Promise<AIResponse> {
    const lastUserMessage =
      messages.filter((m) => m.role === "user").pop()?.content ?? "";

    // Return a structured demo response
    return {
      content: `This is a demonstration response from the HAQ system. In production, this response would be generated by an AI model using the verified rule data and your case information.\n\nYour query: "${lastUserMessage.slice(0, 100)}${lastUserMessage.length > 100 ? "..." : ""}"\n\nNote: AI-generated explanations are supplementary. The deterministic rule-checking engine provides the core timeline calculation independently of any AI provider.`,
      provider: "mock",
      model: "demo-v1",
    };
  }

  async isAvailable(): Promise<boolean> {
    return true;
  }
}

// --------------------------------------------------
// Gemini Provider
// --------------------------------------------------
class GeminiProvider implements AIProvider {
  name = "gemini";
  private apiKey: string;
  private model: string;

  constructor(apiKey: string, model: string = "gemini-3.5-flash") {
    this.apiKey = apiKey;
    this.model = model;
  }

  async generateCompletion(
    messages: AIMessage[],
    options?: { temperature?: number; maxTokens?: number }
  ): Promise<AIResponse> {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${this.model}:generateContent?key=${this.apiKey}`;

    // Convert messages to Gemini format
    const systemInstruction = messages
      .filter((m) => m.role === "system")
      .map((m) => m.content)
      .join("\n\n");

    const contents = messages
      .filter((m) => m.role !== "system")
      .map((m) => ({
        role: m.role === "assistant" ? "model" : "user",
        parts: [{ text: m.content }],
      }));

    try {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 30000);

      const response = await fetch(url, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          ...(systemInstruction
            ? {
                system_instruction: {
                  parts: [{ text: systemInstruction }],
                },
              }
            : {}),
          contents,
          generationConfig: {
            temperature: options?.temperature ?? 0.3,
            maxOutputTokens: options?.maxTokens ?? 2048,
          },
        }),
        signal: controller.signal,
      });

      clearTimeout(timeoutId);

      if (!response.ok) {
        const errorText = await response.text();
        if (response.status === 429) {
          return {
            content: "",
            provider: this.name,
            model: this.model,
            error: "AI rate limit exceeded. Please try again later.",
          };
        }
        if (response.status === 403 || response.status === 401) {
          return {
            content: "",
            provider: this.name,
            model: this.model,
            error: "Invalid or missing AI API key.",
          };
        }
        return {
          content: "",
          provider: this.name,
          model: this.model,
          error: `AI provider error (${response.status}): ${errorText.slice(0, 200)}`,
        };
      }

      const data = await response.json();
      const text =
        data?.candidates?.[0]?.content?.parts?.[0]?.text ?? "";

      if (!text) {
        return {
          content: "",
          provider: this.name,
          model: this.model,
          error: "AI returned an empty response.",
        };
      }

      const cleanText = text.replace(/^#{1,6}\s*/gm, "");
      return {
        content: cleanText,
        provider: this.name,
        model: this.model,
        tokensUsed: data?.usageMetadata?.totalTokenCount,
      };
    } catch (err: unknown) {
      if (err instanceof Error && err.name === "AbortError") {
        return {
          content: "",
          provider: this.name,
          model: this.model,
          error: "AI request timed out after 30 seconds.",
        };
      }
      return {
        content: "",
        provider: this.name,
        model: this.model,
        error: `AI request failed: ${err instanceof Error ? err.message : "Unknown error"}`,
      };
    }
  }

  async isAvailable(): Promise<boolean> {
    return !!this.apiKey;
  }
}

// --------------------------------------------------
// Factory
// --------------------------------------------------

let cachedProvider: AIProvider | null = null;

export function getAIProvider(): AIProvider {
  if (cachedProvider) return cachedProvider;

  const geminiKey = process.env.GEMINI_API_KEY;
  if (geminiKey) {
    cachedProvider = new GeminiProvider(
      geminiKey,
      process.env.GEMINI_MODEL || "gemini-3.5-flash"
    );
    return cachedProvider;
  }

  // Fallback to mock
  cachedProvider = new MockAIProvider();
  return cachedProvider;
}

/** Reset the cached provider (for testing) */
export function resetAIProvider(): void {
  cachedProvider = null;
}

