// Explanation Generator
// --------------------------------------------------
import type { RuleCheckResult, OfficialRule } from "./types";

export async function generateExplanation(
  result: RuleCheckResult,
  rule: OfficialRule
): Promise<AIResponse> {
  const provider = getAIProvider();

  const systemPrompt = `You are HAQ, a citizen-service verification assistant. Your role is to explain government service rule-check results in clear, plain language.

IMPORTANT RULES:
1. Only use facts from the provided rule data and citizen inputs — never invent URLs, legal provisions, page numbers, or quotations.
2. Clearly distinguish between verified facts and reference data that should be cross-checked on official portals.
3. State that this is informational assistance, not legal advice.
4. Keep explanations concise, structured, and actionable.
5. Use Hindi terms in parentheses where helpful for Indian citizens.
6. Do NOT claim any legal violation has occurred based solely on a timeline difference.
7. Do NOT use markdown heading hashtags like '#', '##', or '###' in your response. Instead, write clear headings in bold like **हेडिंग** or on new lines.`;

  const userPrompt = `Please explain this rule-check result to a citizen in plain language:

RULE INFORMATION:
- Title: ${rule.ruleTitle}
- Rule Text: ${rule.ruleText}
- Source: ${rule.sourceUrl}
- Verification Status: ${rule.verificationStatus}
- Deadline: ${rule.deadlineValue} ${rule.deadlineUnit}
- Deadline Basis: ${rule.deadlineBasis}

CHECK RESULT:
- Status: ${result.status}
- Explanation: ${result.explanation}
${result.calculation ? `
CALCULATION:
- Start Date: ${result.calculation.startDate}
- Deadline Date: ${result.calculation.deadlineDate}
- Elapsed Days: ${result.calculation.elapsedDays}
- Allowed Days: ${result.calculation.allowedDays}
- Difference: ${result.calculation.differencedays} days
- Basis Used: ${result.calculation.basisUsed}
` : "No calculation was performed."}

CAVEATS: ${result.caveats.join("; ")}

${result.isSyntheticData ? "⚠️ Note: This uses reference data grounded in official Rajasthan government publications. Always verify on primary portals before taking formal action." : ""}

Please provide:
1. A clear summary of what the rule states
2. What the citizen's provided information shows
3. What the calculation found (if applicable)
4. Important caveats
5. Recommended next steps`;

  return provider.generateCompletion([
    { role: "system", content: systemPrompt },
    { role: "user", content: userPrompt },
  ]);
}
